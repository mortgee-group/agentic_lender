"""Blockchain connectivity utilities for Agentic Lender."""

import json
import os
from pathlib import Path
import hashlib
from datetime import date, datetime
from decimal import Decimal
from web3 import Web3


# Hardhat runs locally on port 8545 by default.
DEFAULT_RPC_URL = "http://127.0.0.1:8545"

# Locate the compiled Solidity contract ABI.
CONTRACT_ARTIFACT = (
    Path(__file__).resolve().parent.parent
    / "blockchain"
    / "artifacts"
    / "contracts"
    / "LoanNote.sol"
    / "LoanNote.json"
)


def get_web3() -> Web3:
    """Create a connection to the configured EVM blockchain."""

    # Allow the RPC endpoint to be configured for local or Docker use.
    rpc_url = os.getenv("BLOCKCHAIN_RPC_URL", DEFAULT_RPC_URL)

    web3 = Web3(Web3.HTTPProvider(rpc_url))

    # Fail clearly if the blockchain node is unavailable.
    if not web3.is_connected():
        raise ConnectionError(
            f"Cannot connect to blockchain at {rpc_url}"
        )

    return web3


def get_loan_contract(web3: Web3):
    """Load the deployed LoanNote contract using its compiled ABI."""

    # The deployed address is supplied through environment configuration.
    contract_address = os.getenv("LOAN_NOTE_CONTRACT_ADDRESS")

    if not contract_address:
        raise ValueError(
            "LOAN_NOTE_CONTRACT_ADDRESS is not configured"
        )

    # Verify the address format before attempting contract interaction.
    if not Web3.is_address(contract_address):
        raise ValueError("Invalid LoanNote contract address")

    checksum_address = Web3.to_checksum_address(contract_address)

    # Ensure that a contract is actually deployed at this address.
    if not web3.eth.get_code(checksum_address):
        raise ValueError(
            "No contract deployed at the configured address"
        )

    # Read the ABI generated by Hardhat during Solidity compilation.
    if not CONTRACT_ARTIFACT.exists():
        raise FileNotFoundError(
            f"LoanNote artifact not found: {CONTRACT_ARTIFACT}"
        )

    with CONTRACT_ARTIFACT.open("r", encoding="utf-8") as file:
        artifact = json.load(file)

    # Construct a Web3 contract object for calling Solidity functions.
    return web3.eth.contract(
        address=checksum_address,
        abi=artifact["abi"],
    )


def generate_audit_hash(
    credit_memo: dict | str,
    valuation_data: dict,
    underwriter_approval: dict,
) -> str:
    """
    Generate a SHA-256 digest of the final mortgage lending evidence.

    The hash combines the AI credit memorandum, property valuation,
    and human underwriter approval into one verifiable audit record.
    """

    def serialize_value(value):
        """Convert Firestore-compatible values into JSON-safe values."""

        # Convert Firestore timestamps into ISO 8601 strings.
        if isinstance(value, (datetime, date)):
            return value.isoformat()

        # Preserve decimal values without floating-point rounding.
        if isinstance(value, Decimal):
            return str(value)

        raise TypeError(
            f"Unsupported audit evidence type: {type(value).__name__}"
        )

    # Combine all required lending evidence into one audit record.
    audit_record = {
        "creditMemorandum": credit_memo,
        "valuationData": valuation_data,
        "underwriterApproval": underwriter_approval,
    }

    # Serialize consistently so identical evidence produces identical bytes.
    canonical_json = json.dumps(
        audit_record,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        default=serialize_value,
        allow_nan=False,
    )

    # SHA-256 produces a 32-byte digest, matching Solidity's bytes32 type.
    return "0x" + hashlib.sha256(
        canonical_json.encode("utf-8")
    ).hexdigest()